from abc import ABC


class abstract_manager(ABC):
    """Абстрактный базовый класс для менеджеров загрузки и обработки данных.

    Содержит общий контракт: имя файла, флаг загрузки, «сырые» данные
    и методы load / save / convert, которые переопределяются в наследниках.
    """

    _file_name: str = ""
    _is_loaded: bool = False
    _data: dict = {}

    def load(self, file_name: str = "") -> None:
        """Загружает данные из файла.

        Должен быть переопределён в наследниках.

        :param file_name: Имя файла для загрузки. Если пусто — берётся
            значение по умолчанию из наследника.
        """
        pass

    def save(self, file_name: str = "") -> bool:
        """Сохраняет данные в файл.

        Должен быть переопределён в наследниках.

        :param file_name: Имя файла для сохранения. Если пусто — берётся
            значение по умолчанию из наследника.
        :return: True, если запись прошла успешно, иначе False.
        """
        return False

    def convert(self) -> bool:
        """Преобразует «сырые» данные в доменные модели.

        Должен быть переопределён в наследниках.

        :return: True, если преобразование прошло успешно, иначе False.
        """
        return False

    @property
    def is_loaded(self) -> bool:
        """Возвращает признак успешной загрузки данных."""
        return self._is_loaded